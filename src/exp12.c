uint32_t gexp( int n )
{
	int a = (n>>8);

	// div12t1[]/div12t2[] は 21*12+4 = 256 エントリしかないため、そのままでは
	//   a >= 252 (n >= 64512) : div12t2[] のシフト量が 0 で飽和し 1 オクターブ低い値
	//   a >  255 (n >= 65536) : 表の範囲外
	// になる (後者は未定義動作)。44.1kHz ではドラム系音色の o8f+ から音程が狂い
	// 始め、o8a+ 以上は隣接する静的データを読んででたらめな音程になっていた。
	// 修正前は範囲検査が一切なかった。通常の音域はここで抜ける。
	// unsigned で比較すれば負値も同じ 1 回の比較で弾ける。
	if ( (unsigned int)a <= 251 ) {
		int b = div12t1[a];

		return ( expt[b] + ( ( expb[b] * (n&0xff) ) >> 8 ) ) >> div12t2[a];
	}

	if ( a < 0 ) return 0;

	// 表に収まるところまで 1 オクターブ (=12) ずつ下げて引き、下げた分を後で戻す。
	// n&0xff は 12*256 の倍数を引いても変わらないので端数はそのままでよい。
	{
		int k = 0;

		do {
			a -= 12;
			if ( ++k > 10 ) return 0;		// 32bit に収まらない超高音は表現できない
		} while ( a > 251 );

		// ここでは a は 240..251 なので div12t2[a] == 0
		{
			int b = div12t1[a];

			return (uint32_t)( expt[b] + ( ( expb[b] * (n&0xff) ) >> 8 ) ) << k;
		}
	}
}


// Windows の MulDiv() 互換。a * b を 64bit で計算して c で割り、0.5 は 0 から遠い側へ丸める。
// あふれたときと c == 0 のときは -1 を返す (MulDiv と同じ。正しいデータでは起きない)。
int32_t muldiv( int32_t a, int32_t b, int32_t c )
{
	int64_t r;

	if ( c == 0 ) return -1;
	if ( c < 0 ) { a = -a; c = -c; }
	if ( (a < 0) == (b < 0) )
		r = ( (int64_t)a * b + c / 2 ) / c;
	else
		r = ( (int64_t)a * b - c / 2 ) / c;
	if ( r > 2147483647 || r < -2147483647 ) return -1;
	return (int32_t)r;
}
